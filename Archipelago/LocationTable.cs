    /// <summary>
    /// Looks up the Archipelago location ID for a completed campaign mission.
    /// Returns -1 if the mission is not part of the randomizer.
    /// </summary>
    public static long GetMissionCompletionLocation(string missionName)
    {
        return string.IsNullOrEmpty(missionName) || !MissionCompletionByName.TryGetValue(missionName, out var id)
            ? -1
            : id;
    }

    /// <summary>
    /// Looks up the Archipelago location ID for a shop purchase (bomber upgrade slot or crew
    /// equipment). Returns -1 if this specific (slot/gear, item) combination isn't randomized.
    /// </summary>
    public static long GetShopPurchaseLocation(string key)
    {
        return string.IsNullOrEmpty(key) || !ShopPurchaseByKey.TryGetValue(key, out var id)
            ? -1
            : id;
    }
